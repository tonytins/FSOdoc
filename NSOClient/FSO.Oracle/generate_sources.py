"""Writes SnapshotSources.props: the 2017 source files the oracle compiles.

Each FreeSO folder holds files its project doesn't compile, so the list comes
from each project's own <Compile> items, not from a folder wildcard. Run it
again if the project list below changes:

    python3 -I NSOClient/FSO.Oracle/generate_sources.py
"""
import pathlib
import re

ORACLE = pathlib.Path(__file__).resolve().parent
REPOSITORY = ORACLE.parent.parent

# The engine-free FreeSO libraries SimAntics needs, in dependency order.
PROJECTS = [
    "TSOClient/tso.common/FSO.Common.csproj",
    "TSOClient/tso.files/FSO.Files.csproj",
    "TSOClient/tso.vitaboy.model/FSO.Vitaboy.csproj",
    "TSOClient/tso.content/FSO.Content.csproj",
    "TSOClient/tso.vitaboy.engine/FSO.Vitaboy.Engine.csproj",
    "TSOClient/tso.world/FSO.LotView.csproj",
    "TSOClient/tso.sound/FSO.HIT.csproj",
    "TSOClient/tso.simantics/FSO.SimAntics.csproj",
    "Other/libs/TargaImagePCL/TargaImagePCL.csproj",
]

# Files that need libraries the oracle leaves out, and that the VM doesn't use.
EXCLUDED = {
    "TSOClient/tso.common/utils/Base64JsonConverter.cs",  # Newtonsoft.Json
    "TSOClient/tso.common/Audio/MP3Player.cs",            # Mp3Sharp
}


def resolve_ignoring_case(base: pathlib.Path, parts: list[str]) -> list[pathlib.Path]:
    """Every existing path under base whose components match parts, ignoring case.

    Project files were written on Windows, which ignores case. On disk some
    folders exist in two casings (Engine and engine), so a component can match
    more than one directory; the file itself exists under only one of them.
    """
    if not parts:
        return [base]
    head, rest = parts[0], parts[1:]
    if head == "..":
        return resolve_ignoring_case(base.parent, rest)
    if not base.is_dir():
        return []
    matches = []
    for child in sorted(base.iterdir()):
        if child.name.lower() == head.lower():
            matches += resolve_ignoring_case(child, rest)
    return matches


def compile_items(project: pathlib.Path) -> list[str]:
    text = project.read_text(encoding="utf-8-sig")
    items = []
    for include in re.findall(r'<Compile Include="([^"]+)"', text):
        candidates = resolve_ignoring_case(project.parent, include.replace("\\", "/").split("/"))
        if len(candidates) != 1:
            raise SystemExit(f"{project.name}: {include} matches {len(candidates)} files")
        relative = candidates[0].resolve().relative_to(REPOSITORY).as_posix()
        if relative.endswith("Properties/AssemblyInfo.cs") or relative in EXCLUDED:
            continue
        items.append(relative)
    return items


def main() -> None:
    lines = [
        "<!-- Generated by generate_sources.py. Do not edit by hand. -->",
        "<Project>",
        "  <ItemGroup>",
    ]
    for project in PROJECTS:
        lines.append(f"    <!-- {project} -->")
        for item in compile_items(REPOSITORY / project):
            lines.append(f'    <Compile Include="$(SnapshotRoot){item}" Link="Snapshot/{item}" />')
    lines += ["  </ItemGroup>", "</Project>", ""]
    (ORACLE / "SnapshotSources.props").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
